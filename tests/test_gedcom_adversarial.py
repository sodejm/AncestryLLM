def test_manifest_is_a_complete_fictional_catalog() -> None:
    catalog = json.loads(MANIFEST.read_text(encoding="utf-8"))

    assert catalog["schema_version"] == 1
    assert catalog["data_policy"] == "fictional-only"
    entries = catalog["entries"]
    ids = [entry["id"] for entry in entries]
    assert len(ids) == len(set(ids))
    assert {entry["expected"] for entry in entries} == EXPECTED_DISPOSITIONS

    referenced_files: set[str] = set()
    referenced_factories: set[str] = set()
    for entry in entries:
        source = entry["source"]
        assert entry["covers"]
        assert entry["stage"]
        assert source["kind"] in {"file", "file-set", "factory"}
        if source["kind"] == "factory":
            referenced_factories.add(source["factory"])
        else:
            referenced_files.update(source["paths"])

    assert referenced_factories == GENERATED_FACTORIES
    assert referenced_files == {
        "minimal-551.ged",
        "minimal-555.ged",
        "preserve-extensions.ged",
        "xref-source-a.ged",
        "xref-source-b.ged",
    }
    assert all((FIXTURES / relative_path).is_file() for relative_path in referenced_files)


