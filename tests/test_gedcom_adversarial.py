def _minimal_text(
    *,
    version: str = "5.5.5",
    newline: str = "\n",
    name: str = "Zoë /Fiction/",
) -> str:
    """Return one fictional, structurally minimal GEDCOM document."""
    lines = [
        "0 HEAD",
        "1 SOUR AdversarialFactory",
        "1 GEDC",
        f"2 VERS {version}",
        "1 CHAR UTF-8",
        "0 @I1@ INDI",
        f"1 NAME {name}",
        "0 TRLR",
    ]
    return newline.join(lines) + newline


def _write_bytes(tmp_path: Path, name: str, payload: bytes) -> Path:
    """Write a generated byte fixture only inside pytest's temporary directory."""
    path = tmp_path / name
    path.write_bytes(payload)
    return path


def _logical_lines(lines: Sequence[str]) -> tuple[tuple[int, str, str, str], ...]:
    """Canonicalize physical CONC/CONT wrapping into logical GEDCOM values."""
    logical: list[tuple[int, str, str, str]] = []
    for raw in lines:
        parsed = gm.parse_gedcom_line(raw)
        if parsed.tag in {"CONC", "CONT"} and logical and parsed.level == logical[-1][0] + 1:
            level, xref, tag, value = logical[-1]
            separator = "\n" if parsed.tag == "CONT" else ""
            logical[-1] = (level, xref, tag, value + separator + parsed.value)
        else:
            logical.append((parsed.level, parsed.xref, parsed.tag, parsed.value))
    return tuple(logical)


def _canonical_records(
    records: Iterable[gm.GedcomRecord],
    *,
    tags: frozenset[str],
) -> dict[tuple[str, str], tuple[tuple[int, str, str, str], ...]]:
    """Return order-independent logical records for semantic round-trip checks."""
    selected = [record for record in records if record.tag in tags]
    canonical = {(record.tag, record.pointer): _logical_lines(record.lines) for record in selected}
    assert len(canonical) == len(selected), "comparison corpus must use unique record keys"
    return canonical


def _record(source: gm.ParsedSource, tag: str, pointer: str) -> gm.GedcomRecord:
    """Find one record by semantic key in a parsed source."""
    return next(
        record for record in source.records if record.tag == tag and record.pointer == pointer
    )


